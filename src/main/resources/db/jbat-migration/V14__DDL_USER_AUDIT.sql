CREATE TABLE IF NOT EXISTS USER_PROFILE_AUDIT
(
    ID INTEGER NOT NULL,
    USER_ID VARCHAR(50) NOT NULL,
    ACTION VARCHAR(50) NOT NULL,
    STUDY_ID INTEGER,
    LEVEL VARCHAR(50) NOT NULL,
    NEW_VALUE VARCHAR(4000) NOT NULL,
    OLD_VALUE VARCHAR(4000),
    CREATED_BY VARCHAR(50),
    CREATED_DATE TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_BY VARCHAR(50),
    UPDATED_DATE TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP	NOT NULL,
    CONSTRAINT USER_PROFILE_AUDIT_PK PRIMARY KEY (ID),
    CONSTRAINT USER_PROFILE_AUDIT_USERS_FK1 FOREIGN KEY (USER_ID)
    REFERENCES USERS (ID) MATCH SIMPLE
    ON UPDATE NO ACTION ON DELETE NO ACTION
    );

CREATE SEQUENCE SEQ_USER_PROFILE_AUDIT MINVALUE 0 MAXVALUE 999999999999999999
    INCREMENT BY 1 START WITH 1 CACHE 20;

CREATE INDEX IDX_USER_PROFILE_AUDIT_USER_ID ON USER_PROFILE_AUDIT(USER_ID);

INSERT INTO USER_PROFILE_AUDIT
SELECT
    NEXTVAL(' SEQ_USER_PROFILE_AUDIT') ID,
    U.ID USER_ID,
    'ROLE' AS ACTION,
    NULL STUDY_ID,
    'SYSTEM' LEVEL,
    R.NAME NEW_VALUE,
    NULL OLD_VALUE,
    U.CREATED_BY CREATED_BY, U.CREATED_DATE CREATED_DATE,
    U.CREATED_BY UPDATED_BY, U.CREATED_DATE UPDATED_DATE
FROM USERS U, ROLE R, USER_ROLE UR
WHERE  U.ID = UR.USER_ID AND R.ID=UR.ROLE_ID