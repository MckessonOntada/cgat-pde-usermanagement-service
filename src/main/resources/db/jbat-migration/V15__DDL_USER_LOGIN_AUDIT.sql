CREATE TABLE IF NOT EXISTS USER_ACTIVITY_AUDIT
(
    ID INTEGER NOT NULL,
    USER_ID VARCHAR(50) NOT NULL,
    ACTIVITY VARCHAR(50) NOT NULL,
    ACTIVITY_DATE TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CREATED_BY VARCHAR(50),
    CREATED_DATE TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_BY VARCHAR(50),
    UPDATED_DATE TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP	NOT NULL,
    CONSTRAINT USER_ACTIVITY_AUDIT_PK PRIMARY KEY (ID),
    CONSTRAINT USER_ACTIVITY_AUDIT_USERS_FK1 FOREIGN KEY (USER_ID)
    REFERENCES USERS (ID) MATCH SIMPLE
    ON UPDATE NO ACTION ON DELETE NO ACTION
    );

CREATE SEQUENCE SEQ_USER_ACTIVITY_AUDIT MINVALUE 0 MAXVALUE 999999999999999999
    INCREMENT BY 1 START WITH 1 CACHE 20;

CREATE INDEX IDX_USER_ACTIVITY_AUDIT_USER_ID ON USER_ACTIVITY_AUDIT(USER_ID);