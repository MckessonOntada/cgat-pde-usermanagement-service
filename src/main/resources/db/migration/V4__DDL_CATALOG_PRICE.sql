CREATE TABLE IF NOT EXISTS catalog.catalog_price (
   id BIGINT PRIMARY KEY,
   tenant_id VARCHAR(255),
   sold_to_customer VARCHAR(10) NOT NULL,
   sold_to_customer_name VARCHAR(35) NOT NULL,
   ship_to_customer VARCHAR(10) NOT NULL,
   ship_to_customer_name VARCHAR(35) NOT NULL,
   parent_customer VARCHAR(10),
   parent_customer_name VARCHAR(35),
   sales_org VARCHAR(4) NOT NULL,
   dist_channel VARCHAR(2) NOT NULL,
   division VARCHAR(2) NOT NULL,
   sap_material VARCHAR(18) NOT NULL,
   variant VARCHAR(30),
   variant_description VARCHAR(30),
   material_identifier_for_cgat VARCHAR(10) NOT NULL,
   ndc VARCHAR(18) NOT NULL,
   udi VARCHAR(18),
   material_description_in_language_en VARCHAR(40) NOT NULL,
   sell_unit VARCHAR(3) NOT NULL,
   contract_no VARCHAR(10),
   contract_type VARCHAR(4),
   contract_type_description VARCHAR(40),
   contract_valid_from DATE,
   contract_valid_to DATE,
   lead_number_mpb VARCHAR(10),
   buying_group VARCHAR(10),
   buying_group_description VARCHAR(40),
   customer_identifier VARCHAR(3),
   pricing_date DATE NOT NULL,
   net_price NUMERIC(18, 2) NOT NULL,
   regular_price NUMERIC(18, 2),
   contract_price NUMERIC(18, 2),
   wac_price NUMERIC(18, 2) NOT NULL,
   discounts NUMERIC(18, 2),
   fixed_price VARCHAR(1),
   price_340b NUMERIC(18, 2),
   price_unit VARCHAR(5) NOT NULL,
   currency VARCHAR(5) NOT NULL,
   inventory_type VARCHAR(1) NOT NULL,
   minimum_order_quantity VARCHAR(17),
   created_by varchar(50) NULL,
   created_at timestamp NOT NULL,
   updated_by varchar(50) NULL,
   updated_at timestamp NULL
);

CREATE SEQUENCE catalog_price_id_seq START 1 INCREMENT 1;
