CREATE SCHEMA IF NOT EXISTS usermanagement;

CREATE TABLE IF NOT EXISTS usermanagement.diagnosis_code (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(20) NOT NULL,
    long_description TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(255),
    updated_at TIMESTAMP,
    updated_by VARCHAR(255),
    created_by_impersonator VARCHAR(255),
    updated_by_impersonator VARCHAR(255),
    created_by_impersonator_user_name VARCHAR(255),
    created_by_user_name VARCHAR(255)
);

CREATE SEQUENCE IF NOT EXISTS diagnosis_code_sequence
START WITH 1
INCREMENT BY 1
MINVALUE 1
NO MAXVALUE
CACHE 20;

