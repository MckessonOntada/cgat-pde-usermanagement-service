
CREATE TABLE IF NOT EXISTS USERS
(
    ID          				VARCHAR(50) 	NOT NULL,
    FIRST_NAME  				VARCHAR(255) 	UNIQUE NOT NULL,
    MIDDLE_NAME 				VARCHAR(255) 	,
    LAST_NAME	 				VARCHAR(50) 	NOT NULL ,
    SUFFIX						VARCHAR(50)		,
    ADDRESS_1					VARCHAR(255)	NOT NULL,
    ADDRESS_2					VARCHAR(255) 	,
    CITY						VARCHAR(255)	NOT NULL,
    STATE 						VARCHAR(255) 	NOT NULL,
    ZIP 						VARCHAR(255) 	NOT NULL,
    EMAI_ID 					VARCHAR(255) 	NOT NULL,
    PHONE_NUMBER 				VARCHAR(255) 	NOT NULL,
    CREATED_DATE				TIMESTAMP(6) 	DEFAULT	CURRENT_TIMESTAMP  	NOT NULL,
    UPDATED_BY					VARCHAR(50)						,
    CONSTRAINT USERS_PK 		PRIMARY KEY (ID)
);


CREATE TABLE IF NOT EXISTS Practices
(
	ID							VARCHAR(255)	NOT NULL	,
    PRACTICE_NAME           	VARCHAR(255) 	UNIQUE NOT NULL	,
    PRACTICE_LOGO_URL       	VARCHAR(255) 	,
    CONTACT_FIRST_NAME  		VARCHAR(50) 	NOT NULL		,
    CONTACT_MIDDLE_NAME	    	VARCHAR(50)		,
    CONTACT_LAST_NAME 			VARCHAR(50) 	NOT NULL		,
    ADDRESS_1					VARCHAR(255) 	NOT NULL		,
    ADDRESS_2					VARCHAR(255) 	,
    CITY						VARCHAR(50) 	NOT NULL		,
    STATE						VARCHAR(50) 	NOT NULL		,
    ZIP							VARCHAR(50) 	NOT NULL		,
    EMAIL						VARCHAR(50) 	NOT NULL		,
    PHONE_NUMBER				VARCHAR(50) 	NOT NULL		,
    FAX							VARCHAR(50) 					,
    CREATED_DATE				TIMESTAMP(6) 	DEFAULT	CURRENT_TIMESTAMP  	NOT NULL,
    UPDATED_BY					VARCHAR(50)						,
    CONSTRAINT PRACTICES_PK 	PRIMARY KEY (ID)
);